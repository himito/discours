/**
 * Writes `docs/components.md`: the Vue components and screens, documented from their source.
 *
 * @remarks TypeDoc can't read `.vue` files, so `npm run docs` runs this first and TypeDoc adds the
 * page to the API documentation (`projectDocuments` in `typedoc.json`). For each `.vue` file the
 * page shows:
 *
 * - the TSDoc comment at the top of `<script setup>`;
 * - its props, with their types and comments (`defineProps<{ … }>()`);
 * - its events (`defineEmits`) and exposed methods (`defineExpose`);
 * - for screens, the route that shows them (from `src/router/index.ts`).
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const OUT = 'docs/components.md'
const GROUPS = [
  { dir: 'src/views', title: 'Screens' },
  { dir: 'src', title: 'Root', only: ['App.vue'] },
  { dir: 'src/components', title: 'Components' },
]

/** Text of a `/** … *\/` comment, without its stars. */
const commentText = (c) =>
  c
    .replace(/^\/\*\*\s*/, '')
    .replace(/\s*\*\/$/, '')
    .split('\n')
    .map((l) => l.replace(/^\s*\* ?/, ''))
    .join('\n')
    .trim()

/** Turns `@remarks` into a paragraph break and drops the other block tags' markers. */
const tidy = (doc) =>
  doc.replace(/^@remarks\s*/m, '').replace(/\{@link\s+([^}|]+?)(?:\s*\|[^}]*)?\}/g, '`$1`')

/** Path → route of each screen, read from the router. */
function routes() {
  const src = readFileSync('src/router/index.ts', 'utf8')
  const out = {}
  for (const m of src.matchAll(
    /path:\s*'([^']+)'[^}]*?(?:component:\s*(\w+)|import\('@\/views\/(\w+)\.vue'\))/g,
  ))
    out[m[2] ?? m[3]] = m[1]
  return out
}

/** Members of a `{ … }` type literal: name, optional flag, type and comment. */
function members(body) {
  const out = []
  const re = /(\/\*\*[\s\S]*?\*\/\s*)?(\w+)(\?)?:\s*([^\n]+)/g
  for (const m of body.matchAll(re))
    out.push({
      name: m[2],
      optional: !!m[3],
      type: m[4].trim(),
      doc: m[1] ? commentText(m[1].trim()) : '',
    })
  return out
}

const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n+/g, ' ')

function describe(file, route) {
  const src = readFileSync(file, 'utf8')
  const script = src.match(/<script setup[^>]*>([\s\S]*?)<\/script>/)?.[1] ?? ''
  const name = file.split('/').pop().replace('.vue', '')
  const lines = [`### ${name}`, '', `\`${file}\`${route ? ` · route \`${route}\`` : ''}`, '']

  const head = script.match(/^\s*(\/\*\*[\s\S]*?\*\/)/)
  if (head) lines.push(tidy(commentText(head[1])), '')

  const props = script.match(/defineProps<\{([\s\S]*?)\}>\(\)/)
  if (props) {
    lines.push('**Props**', '', '| Name | Type | Description |', '| --- | --- | --- |')
    for (const p of members(props[1]))
      lines.push(
        `| \`${p.name}\`${p.optional ? '?' : ''} | \`${cell(p.type)}\` | ${cell(tidy(p.doc))} |`,
      )
    lines.push('')
  }
  const emits = script.match(/(\/\*\*[\s\S]*?\*\/)?\s*const \w+ = defineEmits<\{([\s\S]*?)\}>\(\)/)
  if (emits) {
    lines.push('**Events**', '')
    for (const e of members(emits[2])) lines.push(`- \`${e.name}\` — payload \`${e.type}\``)
    if (emits[1]) lines.push('', tidy(commentText(emits[1])))
    lines.push('')
  }
  const exposed = script.match(/defineExpose\(\{([^}]*)\}\)/)
  if (exposed) {
    const names = exposed[1]
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
    lines.push('**Exposed**', '')
    for (const n of names) {
      const doc = script.match(
        new RegExp(`(/\\*\\*[\\s\\S]*?\\*/)\\s*(?:async\\s+)?function ${n}\\b`),
      )
      lines.push(`- \`${n}()\`${doc ? ` — ${cell(tidy(commentText(doc[1])))}` : ''}`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

const byView = routes()
const parts = [
  '---',
  'title: Vue components',
  '---',
  '',
  '# Vue components',
  '',
  'Generated by `scripts/docs-components.mjs` from the comments in the `.vue` files.',
  '',
]
for (const g of GROUPS) {
  const files = readdirSync(g.dir)
    .filter((f) => f.endsWith('.vue') && (!g.only || g.only.includes(f)))
    .sort()
  if (!files.length) continue
  parts.push(`## ${g.title}`, '')
  for (const f of files) parts.push(describe(join(g.dir, f), byView[f.replace('.vue', '')]), '')
}
mkdirSync('docs', { recursive: true })
writeFileSync(OUT, parts.join('\n').replace(/\n{3,}/g, '\n\n'))
console.log(`✓ ${OUT}`)
