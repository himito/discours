/**
 * Writes `docs/components.md`: the Vue components and screens, documented from their source.
 *
 * @remarks TypeDoc can't read `.vue` files, so `npm run docs` runs this first and TypeDoc adds the
 * page to the API documentation (`projectDocuments` in `typedoc.json`). For each `.vue` file the
 * page shows:
 *
 * - the TSDoc comment at the top of `<script setup>`;
 * - its props, with their types and comments (`defineProps<{ … }>()`);
 * - its events (`defineEmits`) and exposed methods (`defineExpose`);
 * - for screens, the route that shows them (from `src/ui/router/index.ts`).
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = 'docs/components.md'
const ROUTER = 'src/ui/router/index.ts'

/** The page's sections: which `.vue` files go under which title. */
const GROUPS = [
  { dir: 'src/ui/views', title: 'Screens' },
  { dir: 'src/ui', title: 'Root', only: ['App.vue'] },
  { dir: 'src/ui/components', title: 'Components' },
]

const PAGE_HEADER = [
  '---',
  'title: Vue components',
  '---',
  '',
  '# Vue components',
  '',
  'Generated by `scripts/docs-components.mjs` from the comments in the `.vue` files.',
  '',
]

/** A route of the router: its path and the view it shows (a static or a lazy import). */
const ROUTE = /path:\s*'([^']+)'[^}]*?(?:component:\s*(\w+)|import\('@\/ui\/views\/(\w+)\.vue'\))/g
const SCRIPT_SETUP = /<script setup[^>]*>([\s\S]*?)<\/script>/
const LEADING_COMMENT = /^\s*(\/\*\*[\s\S]*?\*\/)/
const PROPS = /defineProps<\{([\s\S]*?)\}>\(\)/
const EMITS = /(\/\*\*[\s\S]*?\*\/)?\s*const \w+ = defineEmits<\{([\s\S]*?)\}>\(\)/
const EXPOSE = /defineExpose\(\{([^}]*)\}\)/
/** A member of a type literal, with its optional doc comment: `/** … *\/ name?: type`. */
const TYPE_MEMBER = /(\/\*\*[\s\S]*?\*\/\s*)?(\w+)(\?)?:\s*([^\n]+)/g

/**
 * A member of a type literal (a prop or an event).
 *
 * @typedef {{ name: string, optional: boolean, type: string, doc: string }} Member
 */

/**
 * What the page shows about a component.
 *
 * @typedef {{
 *   name: string,
 *   file: string,
 *   route: string | undefined,
 *   description: string,
 *   props: Member[] | null,
 *   events: { members: Member[], doc: string } | null,
 *   exposed: { name: string, doc: string }[] | null,
 * }} ComponentDoc
 */

main()

function main() {
  const routes = readRoutes()
  const sections = GROUPS.map((group) => ({
    title: group.title,
    components: vueFilesIn(group).map((file) =>
      parseComponent(file, routes.get(basename(file, '.vue'))),
    ),
  }))
    .filter((section) => section.components.length)
    .map((section) => renderSection(section.title, section.components))
  const page = [...PAGE_HEADER, ...sections].join('\n')
  write(OUTPUT, page.replace(/\n{3,}/g, '\n\n'))
  console.log(`✓ ${OUTPUT}`)
}

// ---------------------------------------------------------------- reading

/** View name → route path, read from the router. */
function readRoutes() {
  const source = read(ROUTER)
  return new Map(
    [...source.matchAll(ROUTE)].map(([, path, view, lazyView]) => [view ?? lazyView, path]),
  )
}

/** The `.vue` files of a group, sorted, as paths relative to the project root. */
function vueFilesIn({ dir, only }) {
  return readdirSync(resolve(PROJECT_ROOT, dir))
    .filter((name) => name.endsWith('.vue') && (!only || only.includes(name)))
    .sort()
    .map((name) => join(dir, name))
}

/**
 * Extracts what the page shows from a component's `<script setup>`.
 *
 * @param {string} file - Path relative to the project root.
 * @param {string | undefined} route - Path of the route showing it, for screens.
 * @returns {ComponentDoc}
 */
function parseComponent(file, route) {
  const script = read(file).match(SCRIPT_SETUP)?.[1] ?? ''
  const head = script.match(LEADING_COMMENT)
  const props = script.match(PROPS)
  const emits = script.match(EMITS)
  const expose = script.match(EXPOSE)
  return {
    name: basename(file, '.vue'),
    file,
    route,
    description: head ? tidy(commentText(head[1])) : '',
    props: props ? typeMembers(props[1]) : null,
    events: emits
      ? { members: typeMembers(emits[2]), doc: emits[1] ? tidy(commentText(emits[1])) : '' }
      : null,
    exposed: expose ? exposedFunctions(expose[1], script) : null,
  }
}

/**
 * The members of a `{ … }` type literal.
 *
 * @returns {Member[]}
 */
function typeMembers(body) {
  return [...body.matchAll(TYPE_MEMBER)].map(([, comment, name, optional, type]) => ({
    name,
    optional: !!optional,
    type: type.trim(),
    doc: comment ? commentText(comment.trim()) : '',
  }))
}

/** The functions passed to `defineExpose`, with the comment above their declaration. */
function exposedFunctions(list, script) {
  return list
    .split(',')
    .map((name) => name.trim())
    .filter(Boolean)
    .map((name) => {
      const declaration = new RegExp(`(/\\*\\*[\\s\\S]*?\\*/)\\s*(?:async\\s+)?function ${name}\\b`)
      const comment = script.match(declaration)?.[1]
      return { name, doc: comment ? tidy(commentText(comment)) : '' }
    })
}

/** Text of a `/** … *\/` comment, without its stars. */
function commentText(comment) {
  return comment
    .replace(/^\/\*\*\s*/, '')
    .replace(/\s*\*\/$/, '')
    .split('\n')
    .map((line) => line.replace(/^\s*\* ?/, ''))
    .join('\n')
    .trim()
}

/** Drops the `@remarks` tag and turns `{@link X}` into code. */
function tidy(doc) {
  return doc.replace(/^@remarks\s*/m, '').replace(/\{@link\s+([^}|]+?)(?:\s*\|[^}]*)?\}/g, '`$1`')
}

// ---------------------------------------------------------------- rendering

/** A `##` section with its components. */
function renderSection(title, components) {
  return [`## ${title}`, '', ...components.flatMap((c) => [renderComponent(c), ''])].join('\n')
}

/**
 * A component's `###` entry.
 *
 * @param {ComponentDoc} component
 */
function renderComponent(component) {
  const where = `\`${component.file}\`${component.route ? ` · route \`${component.route}\`` : ''}`
  const lines = [`### ${component.name}`, '', where, '']
  if (component.description) lines.push(component.description, '')
  if (component.props) lines.push(...renderProps(component.props))
  if (component.events) lines.push(...renderEvents(component.events))
  if (component.exposed) lines.push(...renderExposed(component.exposed))
  return lines.join('\n')
}

/** @param {Member[]} props */
function renderProps(props) {
  return [
    '**Props**',
    '',
    '| Name | Type | Description |',
    '| --- | --- | --- |',
    ...props.map(
      (p) =>
        `| \`${p.name}\`${p.optional ? '?' : ''} | \`${cell(p.type)}\` | ${cell(tidy(p.doc))} |`,
    ),
    '',
  ]
}

/** @param {{ members: Member[], doc: string }} events */
function renderEvents({ members, doc }) {
  return [
    '**Events**',
    '',
    ...members.map((e) => `- \`${e.name}\` — payload \`${e.type}\``),
    ...(doc ? ['', doc] : []),
    '',
  ]
}

/** @param {{ name: string, doc: string }[]} exposed */
function renderExposed(exposed) {
  return [
    '**Exposed**',
    '',
    ...exposed.map(({ name, doc }) => `- \`${name}()\`${doc ? ` — ${cell(doc)}` : ''}`),
    '',
  ]
}

/** Text safe in a Markdown table cell: on one line, with `|` escaped. */
function cell(text) {
  return text.replace(/\|/g, '\\|').replace(/\n+/g, ' ')
}

// ---------------------------------------------------------------- files

/** Reads a file, by its path relative to the project root. */
function read(path) {
  return readFileSync(resolve(PROJECT_ROOT, path), 'utf8')
}

/** Writes a file, by its path relative to the project root, creating its folder. */
function write(path, content) {
  const target = resolve(PROJECT_ROOT, path)
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, content)
}
